// HOST script (Node, desktop) — regenerates `src/desktop-fixtures.ts`.
//
// Criteria 20 and 21 both ask the same kind of question: does the phone compute
// the same bytes the desktop does. The only way that question is worth asking is
// if the expected value comes from the DESKTOP's implementation — `node:crypto`
// and `Buffer` are literally what core calls (`download/wbi.ts:67`,
// `sync/file-ops.ts:342`, `download/lyrics/shared.ts:93`, and every
// `Buffer.byteLength` in `sync/`). A fixture the device generated for itself
// would prove only that it agrees with itself.
//
// This runs on the desktop and never ships: it is the same arrangement as the
// WBI three-piece fixture criterion 23 uses (subplan §1.3, guard header).
//
//   node scripts/make-desktop-fixtures.mjs
//
// Large inputs are described as `seed × repeats` rather than embedded, so a
// 256KB sample costs nothing in the bundle and both sides build the identical
// string.

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// NOT under a `fixtures/` directory on purpose: the repo's .gitignore drops
// `spikes/**/fixtures/` (binary media from the M0 spike), and this file has to
// be committed — it is the record of what the phone was checked against.
const OUT = fileURLToPath(new URL('../src/desktop-fixtures.ts', import.meta.url));

const md5 = (s) => createHash('md5').update(s, 'utf-8').digest('hex');
const sha256 = (s) => createHash('sha256').update(s, 'utf-8').digest('hex');

// ─── digests ────────────────────────────────────────────

// The shape `signWbi` hashes: the sorted query plus the 32-char mixin key
// (wbi.ts:55-70). Length is what matters for the measurement, so this is a real
// playurl query rather than a short word.
const WBI_QUERY =
  'bvid=BV1xx411c7mD&cid=1234567890&fnval=4048&fnver=0&fourk=1&otype=json&' +
  'platform=pc&qn=0&wts=1700000000' +
  '7cd084941338484aae1ad9425b84077c4932caff0ff746eab6f01bf08b70ac45';

// An LRC of the size lark actually stores, and the 256KB stress the plan names.
const LRC_LINE = '[00:12.34]床前明月光，疑是地上霜 — a bilingual lyric line\n';
const LRC_REPEATS = 80; // ~4KB
const BULK_SEED = 'lark-'.repeat(13); // 65 bytes, no multibyte: 256KB stays exact
const BULK_REPEATS = Math.round((256 * 1024) / BULK_SEED.length);

const lrc = LRC_LINE.repeat(LRC_REPEATS);
const bulk = BULK_SEED.repeat(BULK_REPEATS);

// ─── UTF-8 byte length (the TextEncoding port) ──────────

const UTF8_SAMPLES = [
  { name: 'ascii', text: 'plain ascii payload' },
  { name: 'chinese', text: '歌曲名字与艺人' },
  { name: 'surrogate pair', text: '🎵🎧🎼' },
  { name: 'combining marks', text: 'é à ñ' },
  { name: 'lone surrogate', text: 'before\uD83Dafter' },
  { name: 'mixed json', text: JSON.stringify({ name: '歌曲 🎵', artist: 'Ärtist' }) },
];

// ─── base64 (the Base64 port) ───────────────────────────
//
// core's `decodeBase64` (lyrics/shared.ts:93) feeds QQ's and Kugou's answers
// straight to `Buffer.from(v, 'base64')`, which is LENIENT: it skips characters
// outside the alphabet, accepts missing padding, and accepts both alphabets.
// `atob` is not. Whatever the phone ends up using has to answer for these, so
// the fixture records what the desktop does — including where it produces
// garbage, because "returns garbage" and "throws" are different behaviours at
// a call site wrapped in try/catch.

const BASE64_SAMPLES = [
  { name: 'padded', input: Buffer.from('床前明月光', 'utf-8').toString('base64') },
  {
    name: 'unpadded',
    input: Buffer.from('床前明月光', 'utf-8').toString('base64').replace(/=+$/, ''),
  },
  {
    name: 'newlines inside',
    input: Buffer.from('lyrics line', 'utf-8')
      .toString('base64')
      .replace(/^(.{4})/, '$1\n'),
  },
  { name: 'illegal character', input: 'aGVs!bG8=' },
  { name: 'url-safe alphabet', input: Buffer.from([0xfb, 0xff, 0xbf]).toString('base64url') },
  { name: 'length 1 mod 4', input: 'aGVsbG8' + 'X' },
  { name: 'empty', input: '' },
];

const base64Cases = BASE64_SAMPLES.map((s) => {
  const bytes = Buffer.from(s.input, 'base64');
  return {
    name: s.name,
    input: s.input,
    bytesHex: bytes.toString('hex'),
    utf8: bytes.toString('utf-8'),
  };
});

// ─── emit ───────────────────────────────────────────────

const body = `// GENERATED by scripts/make-desktop-fixtures.mjs — do not edit by hand.
//
// Expected values computed on the DESKTOP by the implementations core actually
// calls (\`node:crypto\`, \`Buffer\`). The device compares against these; a device
// that generated its own expectations would only be agreeing with itself.

export interface DigestFixture {
  /** Built as \`seed.repeat(repeats)\` on both sides. */
  seed: string;
  repeats: number;
  bytes: number;
  md5?: string;
  sha256: string;
}

export const WBI_QUERY = ${JSON.stringify(WBI_QUERY)};
export const WBI_QUERY_MD5 = ${JSON.stringify(md5(WBI_QUERY))};
export const WBI_QUERY_SHA256 = ${JSON.stringify(sha256(WBI_QUERY))};

export const LYRICS_4K: DigestFixture = {
  seed: ${JSON.stringify(LRC_LINE)},
  repeats: ${LRC_REPEATS},
  bytes: ${Buffer.byteLength(lrc, 'utf-8')},
  md5: ${JSON.stringify(md5(lrc))},
  sha256: ${JSON.stringify(sha256(lrc))},
};

export const BULK_256K: DigestFixture = {
  seed: ${JSON.stringify(BULK_SEED)},
  repeats: ${BULK_REPEATS},
  bytes: ${Buffer.byteLength(bulk, 'utf-8')},
  sha256: ${JSON.stringify(sha256(bulk))},
};

export interface Utf8Fixture {
  name: string;
  text: string;
  /** \`Buffer.byteLength(text, 'utf8')\` on the desktop. */
  bytes: number;
}

export const UTF8_FIXTURES: readonly Utf8Fixture[] = ${JSON.stringify(
  UTF8_SAMPLES.map((s) => ({ ...s, bytes: Buffer.byteLength(s.text, 'utf-8') })),
  null,
  2,
)};

export interface Base64Fixture {
  name: string;
  input: string;
  /** What \`Buffer.from(input, 'base64')\` produced, hex-encoded. */
  bytesHex: string;
  /** …and the same bytes decoded as UTF-8, which is what \`decodeBase64\` returns. */
  utf8: string;
}

export const BASE64_FIXTURES: readonly Base64Fixture[] = ${JSON.stringify(base64Cases, null, 2)};
`;

writeFileSync(OUT, body, 'utf-8');
console.log(`wrote ${OUT}`);
console.log(
  `  wbi query ${WBI_QUERY.length} chars, lrc ${Buffer.byteLength(lrc)}B, bulk ${Buffer.byteLength(bulk)}B`,
);
