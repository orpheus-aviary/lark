// D16's Android half, as a config plugin (criterion 26).
//
// `android/` is a CNG product and is not tracked, so the ONLY way to say
// anything about the manifest is from here. This plugin owns the whole backup
// story:
//
//   1. two rule files under `res/xml/` — `dataExtractionRules` for API 31+ and
//      `fullBackupContent` for API 30 and below;
//   2. the two manifest attributes that point at them.
//
// `android:allowBackup="false"` comes from `app.config.ts` (Expo's own
// AllowBackup plugin reads `android.allowBackup`), and it is NOT enough on its
// own: since Android 12 it turns off cloud backup but says nothing about
// device-to-device transfer, which is exactly the path a new phone takes when
// it copies the old one. `<device-transfer>` is the half that covers that, and
// the master plan's D16 note about OEMs ignoring `allowBackup` is why both
// belong here rather than one of them.
//
// expo-secure-store ships its own version of this and installs it by default;
// `app.config.ts` passes `configureAndroidBackup: false` so that it steps
// aside. Two plugins writing the same two attributes is the failure where the
// last one wins and nobody notices.

const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const DATA_EXTRACTION_RULES = 'lark_data_extraction_rules';
const FULL_BACKUP_CONTENT = 'lark_backup_rules';

/**
 * Every domain the platform can hand to a backup, listed explicitly.
 *
 * `device_*` are the device-protected (direct-boot) counterparts. We do not use
 * direct-boot storage today; excluding them anyway costs nothing and means a
 * later `directBootAware` component cannot quietly widen what leaves the
 * device.
 */
const DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
];

const GENERATED_BY = 'generated by plugins/with-backup-rules.js — D16, criterion 26';

/** API 31+. Both sections, because cloud backup and D2D transfer are separate. */
function dataExtractionRulesXml() {
  const excludes = DOMAINS.map((domain) => `        <exclude domain="${domain}" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED_BY} -->
<data-extraction-rules>
    <cloud-backup>
${excludes}
    </cloud-backup>
    <device-transfer>
${excludes}
    </device-transfer>
</data-extraction-rules>
`;
}

/**
 * API ≤30. `allowBackup=false` already covers these versions completely, so
 * this file is belt-and-braces — but D16 asks for it by name, and the frozen
 * measurement device is API 35, which means this one can only ever be checked
 * by reading it. Said plainly in the subplan's §9 rather than implied.
 */
function fullBackupContentXml() {
  const excludes = DOMAINS.map((domain) => `    <exclude domain="${domain}" path="." />`).join(
    '\n',
  );
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED_BY} -->
<full-backup-content>
${excludes}
</full-backup-content>
`;
}

const withBackupRuleFiles = (config) =>
  withDangerousMod(config, [
    'android',
    (config) => {
      const xmlDir = path.join(
        config.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml',
      );
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(
        path.join(xmlDir, `${DATA_EXTRACTION_RULES}.xml`),
        dataExtractionRulesXml(),
        'utf-8',
      );
      fs.writeFileSync(
        path.join(xmlDir, `${FULL_BACKUP_CONTENT}.xml`),
        fullBackupContentXml(),
        'utf-8',
      );
      return config;
    },
  ]);

const withBackupManifestAttributes = (config) =>
  withAndroidManifest(config, (config) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);

    // If something else already claimed these, fail the build. Silently
    // overwriting is how a spike ends up testing somebody else's rules while
    // reporting on ours.
    for (const [attribute, value] of [
      ['android:dataExtractionRules', `@xml/${DATA_EXTRACTION_RULES}`],
      ['android:fullBackupContent', `@xml/${FULL_BACKUP_CONTENT}`],
    ]) {
      const existing = application.$[attribute];
      if (existing !== undefined && existing !== value) {
        throw new Error(
          `[with-backup-rules] ${attribute} is already set to ${existing}. D16 requires this plugin to own both rule files — check that expo-secure-store is configured with configureAndroidBackup: false.`,
        );
      }
      application.$[attribute] = value;
    }

    return config;
  });

module.exports = (config) => withBackupManifestAttributes(withBackupRuleFiles(config));
